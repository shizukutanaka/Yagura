// Package aiverify は AI 生成コードの risk pattern を検出する。
//
// 動機 (v0.25.0):
//   m's harness G0.7 INVARIANT「AI出力検証義務」への直接対応。
//
//   2026 の deep research で集まった統計:
//     - Veracode (100+ LLMs, 80 tasks): 45% of AI-generated code ships OWASP Top-10
//     - Apiiro Fortune 50: 10x security findings, 322% privilege-escalation paths, 40% secrets exposure
//     - CodeRabbit: 1.7× issue multiplier for AI code
//     - Georgia Tech Vibe Security Radar: 74 CVEs traceable to AI tools (2026/03)
//     - METR RCT (2025/07): AI tooling slowed experienced devs by 19% (despite predicting 24% speedup)
//
//   yagura の他 quality_check (一般 lint), secretscan (secrets), gha_audit (CI 設定)
//   と相補的に、"AI-generated 高 risk 箇所" を特定する。
//
// 設計判断 (ADR-0001 ゼロ依存):
//   - regex base の pattern detector (stdlib のみ)
//   - language-agnostic (Go/TS/Py/Rust 等を同 rule で扱う)
//   - AI marker comment (e.g., "// AI generated") を検出、その近傍 (±10 lines) を
//     "AI-generated zone" と扱い severity を 2x multiplier (1.7-1.75x を切り上げ)
//   - 6 category × 4 risk level
//   - dedupe cache 統合可能 (CacheLike interface)
//
// "AI が書いたコードを AI で review してはいけない" (Medium 2026) の助言を尊重し、
// rule base の検出器を採用 (LLM call なし)。これは regex の限界もあるが false positive
// が予測可能で、agent loop で再現性ある audit ができる。
package aiverify

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"regexp"
	"sort"
	"strings"
	"sync"
)

// RiskLevel は finding の重大度。
type RiskLevel string

const (
	// RiskCritical は即時修正が必要な最高リスクの finding (CVSS 9.0+相当)。
	RiskCritical RiskLevel = "CRITICAL"
	// RiskHigh は優先修正が推奨される高リスクの finding。
	RiskHigh RiskLevel = "HIGH"
	// RiskMedium は計画的対応が推奨される中リスクの finding。
	RiskMedium RiskLevel = "MEDIUM"
	// RiskLow は任意対応の低リスクの finding。
	RiskLow RiskLevel = "LOW"
)

// Category は finding 分類。
type Category string

const (
	// CategoryAuth は JWT・パスワードハッシュ・セッション等の認証/認可パターン。
	CategoryAuth Category = "auth"
	// CategoryBilling は Stripe 連携・通貨計算・返金処理等の課金パターン。
	CategoryBilling Category = "billing"
	// CategoryData は SQL mutation・DELETE/DROP 等のデータ操作パターン。
	CategoryData Category = "data"
	// CategoryExternal はタイムアウト未設定の HTTP 呼出等の外部通信パターン。
	CategoryExternal Category = "external"
	// CategoryCrypto は弱乱数・DES/RC4 等の暗号化パターン。
	CategoryCrypto Category = "crypto"
	// CategorySecret はハードコードされた API キー等のシークレットパターン。
	CategorySecret Category = "secret"
	// CategoryAIMark は AI 生成マーカーコメントの検出(近傍行の severity 2x 対象)。
	CategoryAIMark Category = "ai-mark"
)

// Rule は単一検出ルール。
type Rule struct {
	ID       string
	Pattern  *regexp.Regexp
	Category Category
	Risk     RiskLevel
	Message  string
	// Languages = nil なら全言語適用。
	Languages []string
}

// Finding は 1 検出結果。
type Finding struct {
	File     string    `json:"file"`
	Line     int       `json:"line"`
	Column   int       `json:"column,omitempty"`
	RuleID   string    `json:"rule_id"`
	Category Category  `json:"category"`
	Risk     RiskLevel `json:"risk"`
	Message  string    `json:"message"`
	Context  string    `json:"context,omitempty"` // 該当行の trimmed snippet
	AIGen    bool      `json:"ai_gen,omitempty"`  // AI-generated zone 内か
}

// Result は全 scan の集計。
type Result struct {
	FilesScanned int             `json:"files_scanned"`
	TotalLines   int             `json:"total_lines"`
	AIGenLines   int             `json:"ai_gen_lines"`
	Findings     []Finding       `json:"findings"`
	RiskScore    int             `json:"risk_score"` // 0-100
	BySeverity   map[RiskLevel]int `json:"by_severity"`
	ByCategory   map[Category]int  `json:"by_category"`
	HasCritical  bool            `json:"has_critical"`
	// v0.26.0: AI marker を持つが対応 test がない files (testcoverage 統合時)
	AIGenWithoutTests []string `json:"ai_gen_without_tests,omitempty"`
	// dedupe cache 統計 (ScanFilesCached 使用時のみ非ゼロ)
	CacheHits   int `json:"cache_hits,omitempty"`
	CacheMisses int `json:"cache_misses,omitempty"`
}

// aiMarkerRe は AI 生成 marker を検出する。case-insensitive。
//
// 検出例:
//   // AI generated
//   # AI generated (reviewed)
//   // Generated by Claude
//   /* @ai-generated */
//   // Copilot suggestion
//   // GPT-4 generated
var aiMarkerRe = regexp.MustCompile(`(?i)(?:^|[^a-zA-Z0-9_])(ai[ -]?generated|generated by (?:claude|copilot|gpt|chatgpt|cursor)|gpt[\d.-]*\s*generated|@ai-generated|copilot[ -]?suggestion|chatgpt|llm[ -]?generated)`)

// aiZoneRadius は marker の前後何行を "AI-generated zone" とみなすか。
//
// AI が生成した関数は通常 5-30 行。±10 行を保守的に取る。
const aiZoneRadius = 10

// compiledDefaultRules は正規表現を一度だけコンパイルして再利用する。
// 以前は DefaultRules() 呼び出し毎に 20+ 個の regexp.MustCompile が走り、
// scan するファイルごとに同一パターンを再コンパイルしていた。
var compiledDefaultRules = sync.OnceValue(buildDefaultRules)

// DefaultRules は yagura が出荷するデフォルト rule set。
// 返り値は呼び出し毎に独立した slice(backing array は共有しない)。
func DefaultRules() []Rule {
	rs := compiledDefaultRules()
	out := make([]Rule, len(rs))
	copy(out, rs)
	return out
}

