// detectLanguage は path 拡張子から言語を推定する。
func detectLanguage(path string) string {
	switch {
	case strings.HasSuffix(path, ".go"):
		return "go"
	case strings.HasSuffix(path, ".ts"), strings.HasSuffix(path, ".tsx"):
		return "ts"
	case strings.HasSuffix(path, ".js"), strings.HasSuffix(path, ".jsx"):
		return "js"
	case strings.HasSuffix(path, ".py"):
		return "python"
	case strings.HasSuffix(path, ".rs"):
		return "rust"
	case strings.HasSuffix(path, ".java"):
		return "java"
	case strings.HasSuffix(path, ".c"), strings.HasSuffix(path, ".cpp"),
		strings.HasSuffix(path, ".cc"), strings.HasSuffix(path, ".h"),
		strings.HasSuffix(path, ".hpp"):
		return "c"
	default:
		return ""
	}
}

// ruleApplies は rule が language に対して有効か。
func ruleApplies(r Rule, language string) bool {
	if len(r.Languages) == 0 {
		return true
	}
	for _, l := range r.Languages {
		if l == language {
			return true
		}
	}
	return false
}

// findAIZones は content 内の AI marker 出現位置から ±aiZoneRadius 行を
// "AI-generated zone" として集合に追加する。
//
// 戻り値: line number (1-indexed) の set + total AI marker count。
func findAIZones(lines []string) (map[int]bool, int) {
	zones := map[int]bool{}
	markerCount := 0
	for i, line := range lines {
		if aiMarkerRe.MatchString(line) {
			markerCount++
			lineNum := i + 1
			start := lineNum - aiZoneRadius
			if start < 1 {
				start = 1
			}
			end := lineNum + aiZoneRadius
			if end > len(lines) {
				end = len(lines)
			}
			for n := start; n <= end; n++ {
				zones[n] = true
			}
		}
	}
	return zones, markerCount
}

// ScanText は単一 source の content を rule に対して走査する。
func ScanText(path, content string, rules []Rule) []Finding {
	lang := detectLanguage(path)
	lines := strings.Split(content, "\n")
	aiZones, _ := findAIZones(lines)

	var findings []Finding
	for i, line := range lines {
		lineNum := i + 1
		// trim for short context
		ctx := strings.TrimSpace(line)
		if len(ctx) > 120 {
			ctx = ctx[:117] + "..."
		}
		for _, r := range rules {
			if !ruleApplies(r, lang) {
				continue
			}
			loc := r.Pattern.FindStringIndex(line)
			if loc == nil {
				continue
			}
			findings = append(findings, Finding{
				File:     path,
				Line:     lineNum,
				Column:   loc[0] + 1,
				RuleID:   r.ID,
				Category: r.Category,
				Risk:     r.Risk,
				Message:  r.Message,
				Context:  ctx,
				AIGen:    aiZones[lineNum],
			})
		}
	}
	return findings
}

// CacheLike は dedupe.Cache に依存しないための minimal interface。
type CacheLike interface {
	Get(key string) ([]byte, bool)
	Set(key string, value []byte)
}

// Scan は複数 file 一括 scan。後方互換 shim。
func Scan(files map[string]string) Result {
	return scanImpl(files, DefaultRules(), nil)
}

// ScanCached は cache 統合版。同 content の重複 scan を skip。
func ScanCached(files map[string]string, cache CacheLike) Result {
	return scanImpl(files, DefaultRules(), cache)
}

// ScanWithRules はカスタム rule で scan する(v0.26+ で project 毎の rule 拡張用)。
func ScanWithRules(files map[string]string, rules []Rule) Result {
	return scanImpl(files, rules, nil)
}

func scanImpl(files map[string]string, rules []Rule, cache CacheLike) Result {
	res := Result{
		BySeverity: map[RiskLevel]int{},
		ByCategory: map[Category]int{},
	}
	for path, content := range files {
		res.FilesScanned++
		res.TotalLines += countLines(content)

		// AI marker 集計(zone とは別途、行数 metric として)
		lines := strings.Split(content, "\n")
		zones, markers := findAIZones(lines)
		if markers > 0 {
			// 各 marker から ±aiZoneRadius 行を AI gen と扱う
			res.AIGenLines += len(zones)
		}

		var fs []Finding
		if cache != nil {
			cacheKey := cacheKeyFor(path, content)
			if cached, ok := cache.Get(cacheKey); ok {
				if parsed, err := unmarshalFindings(cached); err == nil {
					fs = parsed
					res.CacheHits++
				}
			}
			if fs == nil {
				fs = ScanText(path, content, rules)
				res.CacheMisses++
				if data, err := json.Marshal(fs); err == nil {
					cache.Set(cacheKey, data)
				}
			}
		} else {
			fs = ScanText(path, content, rules)
		}

		for _, f := range fs {
			res.Findings = append(res.Findings, f)
			res.BySeverity[f.Risk]++
			res.ByCategory[f.Category]++
			if f.Risk == RiskCritical {
				res.HasCritical = true
			}
		}
	}

	// deterministic 順
	sortFindings(res.Findings)

	res.RiskScore = computeRiskScore(res.Findings)
	return res
}

// sortFindings は findings を決定論的な全順序で並べる。
//
// 入力は files map を range して作られる(= 走査順が非決定的)。sort.Slice は
// unstable なので、比較キーが全順序でないと「等しい」要素の相対順が走査順に依存し
// 出力が run ごとにブレる。File → Line → Column → RuleID まで tie-break して、
// 同一行に複数ルールがヒットしても順序を一意に確定させる。
func sortFindings(fs []Finding) {
	sort.Slice(fs, func(i, j int) bool {
		a, b := fs[i], fs[j]
		if a.File != b.File {
			return a.File < b.File
		}
		if a.Line != b.Line {
			return a.Line < b.Line
		}
		if a.Column != b.Column {
			return a.Column < b.Column
		}
		return a.RuleID < b.RuleID
	})
}

// computeRiskScore は findings から 0-100 の risk score を算出する。
//
// 重み付け (一般 SCA より AI generated を厳しめに):
//   CRITICAL × 25
//   HIGH     × 10
//   MEDIUM   × 3
//   LOW      × 1
//
// AI-generated zone 内の finding は **2x multiplier** を適用。
// CodeRabbit / Veracode が報告する 1.7-1.75× の issue rate を切り上げ。
//
// 最終 score は 100 で cap。
func computeRiskScore(findings []Finding) int {
	score := 0
	for _, f := range findings {
		var w int
		switch f.Risk {
		case RiskCritical:
			w = 25
		case RiskHigh:
			w = 10
		case RiskMedium:
			w = 3
		case RiskLow:
			w = 1
		}
		if f.AIGen {
			w *= 2
		}
		score += w
	}
	if score > 100 {
		score = 100
	}
	return score
}

// countLines は改行数 + 1(empty trailing line も 1 と数える簡素実装)。
func countLines(content string) int {
	if content == "" {
		return 0
	}
	return strings.Count(content, "\n") + 1
}

// cacheKeyFor は (path, content) から決定論的 cache key を生成する。
// quality_check と独立 namespace ("av:" prefix) を使用。
func cacheKeyFor(path, content string) string {
	h := sha256.Sum256([]byte(content))
	return "av:" + path + ":" + hex.EncodeToString(h[:])
}

func unmarshalFindings(data []byte) ([]Finding, error) {
	var fs []Finding
	err := json.Unmarshal(data, &fs)
	return fs, err
}

// Summary は人間可読 1 行サマリ。
func (r Result) Summary() string {
	var sb strings.Builder
	sb.WriteString("risk_score=")
	sb.WriteString(intToStr(r.RiskScore))
	sb.WriteString(" findings=")
	sb.WriteString(intToStr(len(r.Findings)))
	if c := r.BySeverity[RiskCritical]; c > 0 {
		sb.WriteString(" CRIT=")
		sb.WriteString(intToStr(c))
	}
	if h := r.BySeverity[RiskHigh]; h > 0 {
		sb.WriteString(" HIGH=")
		sb.WriteString(intToStr(h))
	}
	if r.AIGenLines > 0 {
		sb.WriteString(" ai_lines=")
		sb.WriteString(intToStr(r.AIGenLines))
	}
	return sb.String()
}

func intToStr(n int) string {
	if n == 0 {
		return "0"
	}
	var sb strings.Builder
	if n < 0 {
		sb.WriteByte('-')
		n = -n
	}
	digits := []byte{}
	for n > 0 {
		digits = append([]byte{byte('0' + n%10)}, digits...)
		n /= 10
	}
	sb.Write(digits)
	return sb.String()
}

// TestAuditor は testcoverage.Audit 結果の minimal interface(循環 import 回避)。
type TestAuditor interface {
	HasTestFor(path string) bool
}

// AnnotateUntested は scan 結果に test 未対応の AI 生成 file を flag する。
//
// usage:
//
//	res := aiverify.Scan(files)
//	tcRes := testcoverage.Audit(files)
//	res = aiverify.AnnotateUntested(res, files, func(p string) bool {
//	    // testcoverage の HasTest を query
//	    ...
//	})
//
// 副次効果: risk_score が AIGenWithoutTests 件数 × 5 で増加(cap 100)。
func AnnotateUntested(res Result, files map[string]string, hasTest func(path string) bool) Result {
	if hasTest == nil {
		return res
	}
	// AI marker を含む各 file をチェック
	var untested []string
	for path, content := range files {
		lines := strings.Split(content, "\n")
		_, markers := findAIZones(lines)
		if markers == 0 {
			continue // AI marker なし、対象外
		}
		if !hasTest(path) {
			untested = append(untested, path)
		}
	}
	sort.Strings(untested)
	res.AIGenWithoutTests = untested

	// risk_score をさらに加算
	bonus := len(untested) * 5
	res.RiskScore += bonus
	if res.RiskScore > 100 {
		res.RiskScore = 100
	}
	return res
}
